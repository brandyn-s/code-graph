func TestParseRequirementsLockComments(t *testing.T) {
	content := "# comment\n    # indented comment\n\nrequests==2.31.0\n"
	deps := parseRequirementsLock(content)
	if len(deps) != 1 {
		t.Errorf("expected 1 dep, got %d", len(deps))
	}
	if len(deps) == 1 {
		if deps[0].Name != "requests" || deps[0].Version != "2.31.0" {
			t.Errorf("expected requests==2.31.0, got %s==%s", deps[0].Name, deps[0].Version)
		}
	}
}

func TestParsePackageLockJSONScopedPackage(t *testing.T) {
	content := `{"packages":{"":{"name":"app","version":"1.0.0"},"node_modules/@babel/core":{"version":"7.24.0"}}}`
	deps := parsePackageLockJSON(content)
	if len(deps) != 1 {
		t.Fatalf("expected 1 dep, got %d: %v", len(deps), deps)
	}
	if deps[0].Name != "@babel/core" || deps[0].Version != "7.24.0" {
		t.Errorf("expected @babel/core 7.24.0, got %s %s", deps[0].Name, deps[0].Version)
	}
}

func TestParseRequirementsLockWithMarkers(t *testing.T) {
	content := "cffi==1.16.0 ; python_implementation != 'PyPy'\ncryptography==42.0.0\n"
	deps := parseRequirementsLock(content)
	if len(deps) != 2 {
		t.Fatalf("expected 2 deps, got %d: %v", len(deps), deps)
	}
	found := make(map[string]string)
	for _, d := range deps {
		found[d.Name] = d.Version
	}
	if v := found["cffi"]; v != "1.16.0" {
		t.Errorf("expected cffi 1.16.0, got %q (marker should be stripped)", v)
	}
}

