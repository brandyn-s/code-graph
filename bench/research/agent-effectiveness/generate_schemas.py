"""Codegen: emit Python TOOL_SCHEMAS from internal/tools/*.go InputSchema literals.

The 14 schema drifts + 22 missing tools that A3 surfaced are a maintenance
problem: agent_runner.py's TOOL_SCHEMAS dict is hand-written and drifts
from the Go handler's InputSchema. Each drift becomes an
agent-effectiveness regression that the battery only catches AFTER it
ships.

Fix at the source: generate TOOL_SCHEMAS by parsing each handler's
`InputSchema: json.RawMessage(`...`)` literal. The generated file is
committed to the repo; a CI step re-runs the generator and `git diff`
fails the build if drift is detected.

Usage:
    python generate_schemas.py                # writes _generated_tool_schemas.py
    python generate_schemas.py --check-only   # exits non-zero if regeneration would change file
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
except (AttributeError, OSError):
    pass

REPO = Path(__file__).parent.parent.parent.parent
TOOLS_DIR = REPO / "internal" / "tools"
OUT = REPO / "bench" / "research" / "arxiv-bench" / "_generated_tool_schemas.py"

HEADER = '''"""Auto-generated tool schemas. DO NOT EDIT BY HAND.

Generated by bench/research/agent-effectiveness/generate_schemas.py from
the InputSchema json.RawMessage literals in internal/tools/*.go. The CI
gate in .github/workflows/agent-effectiveness.yml runs the generator on
every PR and fails if this file is out of sync with the handler source.

To update: re-run `python bench/research/agent-effectiveness/generate_schemas.py`
and commit the result.
"""
from __future__ import annotations

from typing import Any
'''


# Match: Name: "tool_name" ... InputSchema: json.RawMessage(`...`)
# The InputSchema block uses backticks for raw strings; we extract the
# JSON literal between them.
TOOL_SCHEMA_RE = re.compile(
    r'Name:\s*"([a-z_]+)"[\s\S]*?'
    r'(?:Description:\s*"([^"\\]*(?:\\.[^"\\]*)*)"[\s\S]*?)?'
    r'InputSchema:\s*json\.RawMessage\(`([^`]+)`\)',
    re.MULTILINE,
)


def extract_handlers() -> dict[str, dict]:
    """Walk every internal/tools/*.go and pull out (name, description, schema)."""
    out: dict[str, dict] = {}
    for path in sorted(TOOLS_DIR.glob("*.go")):
        if path.name.endswith("_test.go"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in TOOL_SCHEMA_RE.finditer(text):
            tool, desc_raw, raw_json = m.group(1), m.group(2), m.group(3)
            try:
                schema = json.loads(raw_json)
            except json.JSONDecodeError as e:
                print(f"[WARN] {path.name}: JSON parse fail for tool {tool}: {e}",
                      file=sys.stderr)
                continue
            # Decode Go escape sequences in description if present
            description = ""
            if desc_raw:
                description = (
                    desc_raw
                    .replace('\\"', '"')
                    .replace("\\n", "\n")
                    .replace("\\t", "\t")
                    .replace("\\\\", "\\")
                )
            out[tool] = {
                "description": description,
                "input_schema": schema,
            }
    return out


def render(schemas: dict[str, dict]) -> str:
    """Render the schemas as a Python dict literal in stable order.

    Uses pprint.pformat for the schema body so JSON booleans/null become
    Python True/False/None — json.dumps would emit `false`/`true`/`null`,
    which is valid JSON but a SyntaxError in Python.
    """
    import pprint
    body = "\n\nTOOL_SCHEMAS: dict[str, dict[str, Any]] = {\n"
    for tool in sorted(schemas):
        entry = schemas[tool]
        desc = repr(entry["description"])  # Python-quoted string
        # pprint.pformat with sort_dicts keeps output stable across runs.
        schema_repr = pprint.pformat(
            entry["input_schema"], indent=4, width=100, sort_dicts=True
        )
        # Indent every line so it nests cleanly under "input_schema":
        indented = "\n".join("        " + line if line else line
                             for line in schema_repr.splitlines())
        body += f'    "{tool}": {{\n'
        body += f"        \"description\": {desc},\n"
        body += f"        \"input_schema\":\n{indented},\n"
        body += "    },\n"
    body += "}\n"
    return HEADER + body


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check-only", action="store_true",
                        help="Exit non-zero if regenerating would change the file (CI gate)")
    parser.add_argument("--out", default=str(OUT), help="Output file path")
    args = parser.parse_args()

    schemas = extract_handlers()
    print(f"Extracted {len(schemas)} tool schemas from {TOOLS_DIR.relative_to(REPO)}/")

    rendered = render(schemas)
    out_path = Path(args.out)

    if args.check_only:
        if not out_path.exists():
            print(f"[FAIL] {out_path} does not exist; run generate_schemas.py and commit.",
                  file=sys.stderr)
            return 1
        current = out_path.read_text(encoding="utf-8")
        if current.strip() != rendered.strip():
            print(f"[FAIL] {out_path} is out of sync with handler source.", file=sys.stderr)
            print("Run: python bench/research/agent-effectiveness/generate_schemas.py", file=sys.stderr)
            return 1
        print("[OK] generated tool schemas match handler source")
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(rendered, encoding="utf-8")
    print(f"Wrote {out_path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
