func TestParseGoSum(t *testing.T) {
	content := "github.com/stretchr/testify v1.8.4 h1:abc123=\ngithub.com/stretchr/testify v1.8.4/go.mod h1:abc123=\ngolang.org/x/sync v0.5.0 h1:def456=\ngolang.org/x/sync v0.5.0/go.mod h1:def456=\n"
	deps := parseGoSum(content)
	if len(deps) != 2 {
		t.Fatalf("expected 2 deps, got %d: %v", len(deps), deps)
	}
	// Verify both packages are present (order may vary due to map iteration)
	found := make(map[string]string)
	for _, d := range deps {
		found[d.Name] = d.Version
	}
	if v, ok := found["github.com/stretchr/testify"]; !ok || v != "v1.8.4" {
		t.Errorf("expected testify v1.8.4, got %q", v)
	}
	if v, ok := found["golang.org/x/sync"]; !ok || v != "v0.5.0" {
		t.Errorf("expected sync v0.5.0, got %q", v)
	}
}

func TestParseRequirementsLock(t *testing.T) {
	content := "# autogenerated\nboto3==1.34.0\n    # via -r requirements.in\nbotocore==1.34.0\n    # via boto3\nhttpx==0.27.0\n"
	deps := parseRequirementsLock(content)
	if len(deps) != 3 {
		t.Fatalf("expected 3 deps, got %d: %v", len(deps), deps)
	}
	expected := map[string]string{
		"boto3":    "1.34.0",
		"botocore": "1.34.0",
		"httpx":    "0.27.0",
	}
	for _, d := range deps {
		if v, ok := expected[d.Name]; !ok {
			t.Errorf("unexpected dep: %s", d.Name)
		} else if d.Version != v {
			t.Errorf("dep %s: expected version %s, got %s", d.Name, v, d.Version)
		}
	}
}

func TestParsePackageLockJSON(t *testing.T) {
	content := `{"name":"app","lockfileVersion":3,"packages":{"":{"name":"app","version":"1.0.0"},"node_modules/express":{"version":"4.18.2"},"node_modules/lodash":{"version":"4.17.21"}}}`
	deps := parsePackageLockJSON(content)
	if len(deps) != 2 {
		t.Fatalf("expected 2 deps (excluding root), got %d: %v", len(deps), deps)
	}
	found := make(map[string]string)
	for _, d := range deps {
		found[d.Name] = d.Version
	}
	if v, ok := found["express"]; !ok || v != "4.18.2" {
		t.Errorf("expected express 4.18.2, got %q", v)
	}
	if v, ok := found["lodash"]; !ok || v != "4.17.21" {
		t.Errorf("expected lodash 4.17.21, got %q", v)
	}
}

