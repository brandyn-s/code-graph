func TestParseGoSumMalformedLines(t *testing.T) {
	content := "just-a-name\n\ngithub.com/pkg/errors v0.9.1 h1:abc=\n"
	deps := parseGoSum(content)
	if len(deps) != 1 {
		t.Fatalf("expected 1 dep (malformed line skipped), got %d: %v", len(deps), deps)
	}
	if deps[0].Name != "github.com/pkg/errors" {
		t.Errorf("expected github.com/pkg/errors, got %s", deps[0].Name)
	}
}
