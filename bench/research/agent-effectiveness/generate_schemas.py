"""Codegen: emit Python TOOL_SCHEMAS from registered runtime definitions.

The Go exporter executes the same registration functions as the MCP server,
then emits their in-memory definitions without starting a transport or
invoking a handler. This preserves computed schemas that source regexes cannot
see. The generated file is committed; CI checks it for drift.

Usage:
    python generate_schemas.py                # writes _generated_tool_schemas.py
    python generate_schemas.py --check-only   # exits non-zero if regeneration would change file
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
except (AttributeError, OSError):
    pass

REPO = Path(__file__).parent.parent.parent.parent
OUT = REPO / "bench" / "research" / "agent-effectiveness" / "_generated_tool_schemas.py"
EXPORT_COMMAND = ("go", "run", "./cmd/export-tool-schemas")
CORE_COMMAND = ("go", "run", "./cmd/export-tool-schemas", "--core")

HEADER = '''"""Auto-generated tool schemas. DO NOT EDIT BY HAND.

Generated by bench/research/agent-effectiveness/generate_schemas.py from
the MCP tool definitions registered by internal/tools. The CI gate in
.github/workflows/core-ci.yml runs the generator on every PR and fails if
this file is out of sync with the runtime contract.

To update: re-run `python bench/research/agent-effectiveness/generate_schemas.py`
and commit the result.
"""
from __future__ import annotations

from typing import Any
'''


def extract_handlers() -> dict[str, dict]:
    """Load name, description, and input schema from the Go runtime exporter."""
    try:
        result = subprocess.run(
            EXPORT_COMMAND,
            cwd=REPO,
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
    except OSError as exc:
        command = " ".join(EXPORT_COMMAND)
        raise RuntimeError(
            f"could not execute runtime schema exporter `{command}`: {exc}"
        ) from exc

    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or "no diagnostic output"
        raise RuntimeError(
            "runtime schema exporter failed "
            f"(exit {result.returncode}): {detail}"
        )

    try:
        definitions = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            "runtime schema exporter returned invalid JSON "
            f"at line {exc.lineno}, column {exc.colno}: {exc.msg}"
        ) from exc
    if not isinstance(definitions, list):
        raise RuntimeError(
            "runtime schema exporter returned "
            f"{type(definitions).__name__}; expected a JSON array"
        )

    out: dict[str, dict] = {}
    for index, definition in enumerate(definitions):
        if not isinstance(definition, dict):
            raise RuntimeError(
                f"runtime tool definition at index {index} is not a JSON object"
            )
        name = definition.get("name")
        description = definition.get("description")
        schema = definition.get("inputSchema")
        if not isinstance(name, str) or not name:
            raise RuntimeError(
                f"runtime tool definition at index {index} has no non-empty name"
            )
        if name in out:
            raise RuntimeError(f"runtime schema exporter returned duplicate tool {name!r}")
        if not isinstance(description, str):
            raise RuntimeError(
                f"runtime tool {name!r} has a non-string description"
            )
        if not isinstance(schema, dict):
            raise RuntimeError(
                f"runtime tool {name!r} has a non-object inputSchema"
            )
        out[name] = {
            "description": description,
            "input_schema": schema,
        }
    return out


def extract_core_toolset(all_tools: set[str]) -> list[str]:
    """Load the sorted core toolset from the Go runtime and validate it."""
    result = subprocess.run(
        CORE_COMMAND, cwd=REPO, check=False, capture_output=True, text=True, encoding="utf-8",
    )
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or "no diagnostic output"
        raise RuntimeError(f"core toolset exporter failed (exit {result.returncode}): {detail}")
    names = json.loads(result.stdout)
    if not isinstance(names, list) or not all(isinstance(n, str) for n in names):
        raise RuntimeError("core toolset exporter did not return a JSON array of names")
    unknown = sorted(set(names) - all_tools)
    if unknown:
        raise RuntimeError(f"core toolset names not registered: {unknown}")
    return sorted(names)


def render(schemas: dict[str, dict], core: list[str]) -> str:
    """Render the schemas as a Python dict literal in stable order.

    Uses pprint.pformat for the schema body so JSON booleans/null become
    Python True/False/None — json.dumps would emit `false`/`true`/`null`,
    which is valid JSON but a SyntaxError in Python.
    """
    import pprint
    body = "\n\nTOOL_SCHEMAS: dict[str, dict[str, Any]] = {\n"
    for tool in sorted(schemas):
        entry = schemas[tool]
        desc = repr(entry["description"])  # Python-quoted string
        # pprint.pformat with sort_dicts keeps output stable across runs.
        schema_repr = pprint.pformat(
            entry["input_schema"], indent=4, width=100, sort_dicts=True
        )
        # Indent every line so it nests cleanly under "input_schema":
        indented = "\n".join("        " + line if line else line
                             for line in schema_repr.splitlines())
        body += f'    "{tool}": {{\n'
        body += f"        \"description\": {desc},\n"
        body += f"        \"input_schema\":\n{indented},\n"
        body += "    },\n"
    body += "}\n"
    body += "\n\n# Tools advertised under CODE_GRAPH_TOOLSET=core (the default).\n"
    body += "CORE_TOOLS: frozenset[str] = frozenset({\n"
    for tool in core:
        body += f'    "{tool}",\n'
    body += "})\n"
    return HEADER + body


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check-only", action="store_true",
                        help="Exit non-zero if regenerating would change the file (CI gate)")
    parser.add_argument("--out", default=str(OUT), help="Output file path")
    args = parser.parse_args()

    try:
        schemas = extract_handlers()
    except RuntimeError as exc:
        print(f"[FAIL] {exc}", file=sys.stderr)
        return 1
    try:
        core = extract_core_toolset(set(schemas))
    except (RuntimeError, json.JSONDecodeError) as exc:
        print(f"[FAIL] {exc}", file=sys.stderr)
        return 1
    print(f"Exported {len(schemas)} registered tool schemas ({len(core)} core) from the Go runtime")

    rendered = render(schemas, core)
    out_path = Path(args.out)

    if args.check_only:
        if not out_path.exists():
            print(f"[FAIL] {out_path} does not exist; run generate_schemas.py and commit.",
                  file=sys.stderr)
            return 1
        current = out_path.read_text(encoding="utf-8")
        if current.strip() != rendered.strip():
            print(f"[FAIL] {out_path} is out of sync with handler source.", file=sys.stderr)
            print("Run: python bench/research/agent-effectiveness/generate_schemas.py", file=sys.stderr)
            return 1
        print("[OK] generated tool schemas match handler source")
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(rendered, encoding="utf-8")
    print(f"Wrote {out_path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
